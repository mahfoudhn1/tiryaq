export type IconName = keyof typeof ICONS | (string & {});

interface IconProps {
  name: IconName;
  size?: number;
  color?: string;
  strokeWidth?: number;
}

export function Icon({ name, size = 20, color, strokeWidth = 2 }: IconProps) {
  const { colors } = useTheme();
  const Glyph = ICONS[name] ?? Sparkles;
  return <Glyph size={size} color={color ?? colors.icon} strokeWidth={strokeWidth} />;
}
